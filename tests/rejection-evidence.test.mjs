import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,writeFile,readFile,readdir} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {DecisionOutput} from '../src/decision-output.mjs';
import {rejectedEvidence} from '../src/rejection-evidence.mjs';
test('recovered-attempt evidence redacts credentials and cannot grow without bounds or delete unrelated files',async t=>{
  const runtime=await mkdtemp(join(tmpdir(),'wb-evidence-'));t.after(()=>rm(runtime,{recursive:true,force:true}));
  const credential={accessToken:'PRIVATE_ACCESS_FIXTURE',refreshToken:'PRIVATE_REFRESH_FIXTURE'};
  const output=new DecisionOutput();output.observe({type:'result',result:'bad PRIVATE_ACCESS_FIXTURE PRIVATE_REFRESH_FIXTURE output'});
  const save=attempt=>rejectedEvidence({runtime},{requestId:'fixture',model:'deepseek-v4.1-flash',attempt,errorCode:'invalid_decision',output,credential});
  const first=await save(1),text=await readFile(first,'utf8');assert.ok(!text.includes(credential.accessToken));assert.ok(!text.includes(credential.refreshToken));assert.match(text,/redacted/);
  const unrelated=join(runtime,'rejected-decisions','manual-note.txt');await writeFile(unrelated,'keep');
  for(let attempt=2;attempt<=34;attempt++)await save(attempt);
  assert.equal(await readFile(unrelated,'utf8'),'keep');assert.equal((await readdir(join(runtime,'rejected-decisions'))).filter(f=>f.endsWith('.json')).length,32);
  const huge=new DecisionOutput();huge.observe({type:'result',result:'x'.repeat(1024*1024)});
  const path=await rejectedEvidence({runtime},{requestId:'large',model:'deepseek-v4.1-flash',attempt:1,errorCode:'invalid_decision',output:huge,credential});
  const limited=JSON.parse(await readFile(path,'utf8'));assert.equal(limited.limited,true);assert.equal(limited.result,undefined);assert.ok(limited.summary.outputs[0].sha256);
});
